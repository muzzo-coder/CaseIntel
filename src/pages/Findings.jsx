/**
 * Findings — §17 / Discrepancy & Inconsistency Ledger (/app/findings)
 * Filter bar: Type, Status, Review State.
 * Sorted by confidence score desc.
 * Uses FindingCard, EmptyState, DemoTag, and includes mandatory legal disclaimer.
 */
import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Search } from 'lucide-react';
import { useMatter } from '../context/MatterContext';
import { MOCK_MATTER, MOCK_FINDINGS } from '../mocks/data';
import DemoTag from '../components/ui/DemoTag';
import FindingCard from '../components/ui/FindingCard';
import EmptyState from '../components/ui/EmptyState';

export default function Findings() {
  const navigate = useNavigate();
  const { activeMatter = MOCK_MATTER } = useMatter() || {};
  const matter = activeMatter || MOCK_MATTER;

  const [findings, setFindings] = useState(MOCK_FINDINGS);
  const [typeFilter, setTypeFilter] = useState('all');
  const [reviewFilter, setReviewFilter] = useState('all'); // 'all' | 'unreviewed' | 'confirmed' | 'dismissed'
  const [search, setSearch] = useState('');

  const handleConfirm = (id) => {
    setFindings((prev) =>
      prev.map((f) => (f.id === id ? { ...f, review: { status: 'confirmed' } } : f))
    );
  };

  const handleDismiss = (id) => {
    setFindings((prev) =>
      prev.map((f) => (f.id === id ? { ...f, review: { status: 'dismissed' } } : f))
    );
  };

  const filteredFindings = findings
    .filter((f) => {
      if (typeFilter !== 'all' && f.type !== typeFilter) return false;
      if (reviewFilter === 'unreviewed' && f.review?.status != null) return false;
      if (reviewFilter === 'confirmed' && f.review?.status !== 'confirmed') return false;
      if (reviewFilter === 'dismissed' && f.review?.status !== 'dismissed') return false;
      if (
        search &&
        !f.summary.toLowerCase().includes(search.toLowerCase()) &&
        !f.id.toLowerCase().includes(search.toLowerCase())
      ) {
        return false;
      }
      return true;
    })
    .sort((a, b) => b.score - a.score);

  return (
    <div style={{ minHeight: 'calc(100vh - 56px)', background: 'var(--paper-100)' }}>
      {/* ── Header Band (Black) ── */}
      <header
        style={{
          background: 'var(--ink-950)',
          borderBottom: '1px solid var(--ink-700)',
          padding: '1.25rem 2rem',
        }}
      >
        <div style={{ maxWidth: '1400px', margin: '0 auto', display: 'flex', alignItems: 'center', justifyContent: 'between', gap: '1rem', flexWrap: 'wrap' }}>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem', marginBottom: '0.25rem' }}>
              <span className="case-id" style={{ color: 'var(--gold-400)', fontSize: '0.8125rem' }}>
                {matter.id}
              </span>
              <span style={{ color: 'var(--ink-600)' }}>·</span>
              <span className="meta-label on-black" style={{ fontSize: '0.6875rem' }}>
                CROSS-DOCUMENT FINDINGS
              </span>
              <DemoTag />
            </div>
            <h1
              style={{
                fontFamily: "'Fraunces', Georgia, serif",
                fontSize: '1.5rem',
                fontWeight: 400,
                color: 'var(--paper-0)',
                margin: 0,
              }}
            >
              Identified Inconsistencies
            </h1>
          </div>
          <div style={{ marginLeft: 'auto', display: 'flex', alignItems: 'center', gap: '1rem' }}>
            <div style={{ fontSize: '0.75rem', color: 'var(--ink-400)' }}>
              Candidate inconsistencies generated by Pipeline Stage 5 (DETECT)
            </div>
          </div>
        </div>
      </header>

      {/* ── Filter Bar ── */}
      <div
        style={{
          background: 'var(--paper-0)',
          borderBottom: '1px solid var(--paper-200)',
          padding: '0.75rem 2rem',
        }}
      >
        <div style={{ maxWidth: '1400px', margin: '0 auto', display: 'flex', alignItems: 'center', gap: '1rem', flexWrap: 'wrap' }}>
          {/* Search */}
          <div style={{ position: 'relative', minWidth: '220px' }}>
            <input
              type="text"
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Filter findings…"
              className="input-base"
              style={{ fontSize: '0.75rem', padding: '0.35rem 0.6rem 0.35rem 2rem', width: '100%' }}
            />
            <Search size={13} style={{ position: 'absolute', left: '0.6rem', top: '50%', transform: 'translateY(-50%)', color: 'var(--paper-400)' }} />
          </div>

          {/* Type Filter */}
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.375rem' }}>
            <span className="meta-label" style={{ fontSize: '0.6875rem' }}>TYPE:</span>
            <select
              value={typeFilter}
              onChange={(e) => setTypeFilter(e.target.value)}
              className="input-base"
              style={{ fontSize: '0.75rem', padding: '0.35rem 0.5rem', background: 'var(--paper-50)' }}
            >
              <option value="all">All types</option>
              <option value="date-mismatch">Date Mismatch</option>
              <option value="amount-mismatch">Amount Mismatch</option>
              <option value="entity-mismatch">Entity Mismatch</option>
              <option value="statement-conflict">Statement Conflict</option>
            </select>
          </div>

          {/* Review Filter */}
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.375rem' }}>
            <span className="meta-label" style={{ fontSize: '0.6875rem' }}>HUMAN REVIEW:</span>
            <select
              value={reviewFilter}
              onChange={(e) => setReviewFilter(e.target.value)}
              className="input-base"
              style={{ fontSize: '0.75rem', padding: '0.35rem 0.5rem', background: 'var(--paper-50)' }}
            >
              <option value="all">All states</option>
              <option value="unreviewed">Awaiting Counsel Review</option>
              <option value="confirmed">Confirmed</option>
              <option value="dismissed">Dismissed</option>
            </select>
          </div>

          <div style={{ marginLeft: 'auto', fontFamily: "'IBM Plex Mono'", fontSize: '0.6875rem', color: 'var(--paper-500)' }}>
            SHOWING {filteredFindings.length} OF {findings.length} FINDINGS
          </div>
        </div>
      </div>

      {/* ── Findings Grid/List ── */}
      <div style={{ maxWidth: '1400px', margin: '0 auto', padding: '2rem' }}>
        {filteredFindings.length === 0 ? (
          <div
            style={{
              background: 'var(--paper-0)',
              border: '1px solid var(--paper-200)',
              borderRadius: '2px',
              padding: '3rem',
            }}
          >
            <EmptyState
              object="findings"
              title="No Inconsistencies Found"
              description="No findings matched the selected filters. Change filter criteria or run detection on new exhibits."
            />
          </div>
        ) : (
          <div style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}>
            {filteredFindings.map((finding) => (
              <FindingCard
                key={finding.id}
                finding={finding}
                onOpenDesk={() => navigate(`/app/findings/${finding.id}/compare`)}
                onConfirm={handleConfirm}
                onDismiss={handleDismiss}
              />
            ))}
          </div>
        )}

        {/* Disclaimer */}
        <aside
          role="note"
          style={{
            marginTop: '2.5rem',
            fontSize: '0.75rem',
            color: 'var(--paper-500)',
            borderLeft: '2px solid var(--gold-500)',
            paddingLeft: '0.75rem',
            fontStyle: 'italic',
          }}
        >
          CaseIntel is a research and review aid, NOT legal advice.
        </aside>
      </div>
    </div>
  );
}
